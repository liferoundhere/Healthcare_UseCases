// Builds js/narrative.js from the 2D app's scene data (app/src/scenes.ts), so the 3D stage
// and the 2D schematic share one source of truth: nodes, links, states, narration, facts.
import { buildSync } from '../../app/node_modules/esbuild/lib/main.js';
import { writeFileSync, mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const entry = join(here, '../../app/src/scenes.ts');
const out = join(mkdtempSync(join(tmpdir(), 'narr-')), 'scenes.mjs');
buildSync({ entryPoints: [entry], bundle: true, format: 'esm', outfile: out, logLevel: 'error' });
const { SCENES } = await import(pathToFileURL(out).href);

const slim = SCENES.map((s) => ({
  id: s.id,
  group: s.group,
  title: s.title,
  pillars: s.pillars,
  subtitle: s.subtitle,
  caveat: s.caveat,
  nodes: s.nodes.map((n) => ({ id: n.id, icon: n.icon, title: n.title, sub: n.sub, hidden: !!n.hidden, r: n.r || 30 })),
  zones: s.zones.map((z) => ({ id: z.id, label: z.label, hidden: !!z.hidden, cisco: !!z.cisco })),
  links: s.links.map((l) => ({ id: l.id, a: l.a, b: l.b, bend: l.bend })),
  steps: s.steps,
}));

const body = `// GENERATED by tools/gen_narrative.mjs from app/src/scenes.ts. Do not edit by hand.\nexport const NARR = ${JSON.stringify(slim, null, 1)};\n`;
if (/[\u2014\u2013]/.test(body)) throw new Error('em or en dash found in narrative');
writeFileSync(join(here, '../js/narrative.js'), body);
console.log(`narrative.js: ${slim.length} scenes, ${slim.reduce((a, s) => a + s.steps.length, 0)} steps, ${(body.length / 1024).toFixed(0)} KB`);
