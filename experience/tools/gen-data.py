#!/usr/bin/env python3
"""Generate experience/src/data/sources.ts and research.ts from the research briefs.

Run from the repository root:  python3 experience/tools/gen-data.py
The briefs in research/ stay the source of truth; this only reshapes them for the app.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "research"
OUT = ROOT / "experience" / "src" / "data"

def parse_sources(path, start, end, prefix, group):
    text = (R / path).read_text()
    a = text.index(start)
    b = text.index(end, a) if end and end in text[a:] else len(text)
    out = []
    for m in re.finditer(r"^(\d+)\. (.+?)$", text[a:b], re.M):
        body = m.group(2)
        u = re.search(r"https?://\S+", body)
        title = (body[: u.start()] if u else body).strip().rstrip(".").strip()
        title = re.sub(r"\s*\((?:F|S)\)\s*", " ", title).strip()
        out.append({"id": f"{prefix}{m.group(1)}", "group": group, "title": title, "url": u.group(0).rstrip(").,;") if u else ""})
    m = re.search(r"^\s*- 3b\. (.+?)$", text[a:b], re.M)
    if m:
        u = re.search(r"https?://\S+", m.group(1))
        out.insert(3, {"id": f"{prefix}3b", "group": group, "title": m.group(1)[: u.start()].strip().rstrip("."), "url": u.group(0)})
    return out

src = []
src += parse_sources("05-cisco-cloud-control-data-fabric.md", "## G) Sources", "## H) Gaps", "C", "Cisco Cloud Control and Cisco Data Fabric (brief 05)")
src += parse_sources("06-cloud-control-agentic-orchestrator.md", "## J) Sources", "## K) Gaps", "CC", "Cloud Control as an agentic orchestrator (brief 06)")
src += parse_sources("07-data-fabric-third-party-reach.md", "## J) Sources", "## K) Gaps", "DF", "Data Fabric and third-party reach (brief 07)")
src += parse_sources("08-cisco-healthcare-portfolio.md", "## H) Sources", "## I) Gaps", "HP", "Cisco healthcare portfolio and customers (brief 08)")
src += parse_sources("09-agentic-clinical-and-workplace-ops.md", "## Sources", "## Gaps", "OP", "Agentic clinical and workplace operations (brief 09)")

ts = "/** Generated by tools/gen-data.py from research/05 to 09. Do not edit by hand. */\n"
ts += "export interface Source { id: string; group: string; title: string; url: string }\n"
ts += "export const SOURCES: Source[] = " + json.dumps(src, indent=1, ensure_ascii=False) + ";\n"
ts += "export const SRC = new Map(SOURCES.map((s) => [s.id, s]));\n"
(OUT / "sources.ts").write_text(ts)

cust = json.loads((R / "data" / "healthcare-customers.json").read_text())
keep = ["Dayton Children's", "Community Health Network", "NYC Health + Hospitals", "Rush University System for Health", "Children's National Hospital",
        "Springfield Clinic", "Barts Health NHS Trust", "Mount Sinai Health System", "Bayside Health Peninsula", "Kasugai Municipal Hospital", "Maebashi Red Cross Hospital", "Phuong Dong General Hospital"]
proof = [{"customer": c["customer"], "country": c.get("country", ""), "year": c.get("year"), "products": c["products"], "outcome": c["outcome"], "metric": c.get("metric", ""), "url": c["sourceUrl"]}
         for name in keep for c in cust if c["customer"] == name]

facts = json.loads((R / "data" / "ops-lens-facts.json").read_text())
lens = {"network": "netops", "security": "secops", "clinical": "clinops", "workplace": "workops"}
lf = {}
for f in facts:
    lf.setdefault(lens[f["lens"]], []).append({"value": f["value"], "label": f["label"], "source": f["source"], "url": f["sourceUrl"], "vendor": bool(f["vendorReported"])})

ucmap = json.loads((R / "data" / "usecase-product-map.json").read_text())
ids = ["ehr", "iomt", "ransom", "wifi", "imaging", "home", "wan", "identity", "compliance", "aiwork"]
port = {ids[u["useCase"] - 1]: {"products": [{"name": p["name"], "role": p["role"], "url": p.get("sourceUrl", "")} for p in u["products"]], "partners": u.get("partners", [])} for u in ucmap}

ts = "/** Generated by tools/gen-data.py from research/data/*.json. Do not edit by hand. */\n"
ts += "export interface Proof { customer: string; country: string; year: number | null; products: string[]; outcome: string; metric: string; url: string }\n"
ts += "export const PROOF: Proof[] = " + json.dumps(proof, indent=1, ensure_ascii=False) + ";\n"
ts += "export interface LensFact { value: string; label: string; source: string; url: string; vendor: boolean }\n"
ts += "export const LENS_FACTS: Record<string, LensFact[]> = " + json.dumps(lf, indent=1, ensure_ascii=False) + ";\n"
ts += "export interface Portfolio { products: { name: string; role: string; url: string }[]; partners: string[] }\n"
ts += "/** Cisco's wider portfolio per use case (brief 08), beyond what Cloud Control connects today. */\n"
ts += "export const PORTFOLIO: Record<string, Portfolio> = " + json.dumps(port, indent=1, ensure_ascii=False) + ";\n"
(OUT / "research.ts").write_text(ts)
print(len(src), "sources;", len(proof), "proof points;", {k: len(v) for k, v in lf.items()}, "; portfolio", {k: len(v["products"]) for k, v in port.items()})
